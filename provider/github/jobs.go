package github

import (
	"context"
	"fmt"
	"net/http"
)

// GetWorkflowJob retrieves details for a specific GitHub Actions job.
//
// A job represents a collection of workflow steps executed on a runner.
//
// The caller must have read access to the repository.
//
// Parameters:
//   - ctx: Request context for cancellation and timeouts.
//   - owner: Repository owner or organization.
//   - repo: Repository name.
//   - jobID: Numeric identifier of the workflow job.
//
// Returns the requested job or an error if the request fails, the job does not
// exist, or the API returns a non-success status.
func (c *Client) GetWorkflowJob(ctx context.Context, repo, owner string, jobID int64) ([]Job, error) {
	path := fmt.Sprintf("/repos/%s/%s/actions/jobs/%d", owner, repo, jobID)

	var resp jobListResponse
	if err := c.do(ctx, http.MethodGet, path, nil, &resp); err != nil {
		return nil, fmt.Errorf("failed to get job{%d}: %w", jobID, err)
	}
	return resp.Jobs, nil
}

// DownloadWorkflowJobLogs downloads the logs generated by a GitHub Actions job.
//
// GitHub responds with a redirect to a downloadable archive containing the job
// logs.
//
// The caller must have read access to the repository.
//
// Parameters:
//   - ctx: Request context for cancellation and timeouts.
//   - owner: Repository owner or organization.
//   - repo: Repository name.
//   - jobID: Numeric identifier of the workflow job.
//
// Returns an error if the request fails or the API returns a non-success
// status.
func (c *Client) DownloadWorkflowJobLogs(ctx context.Context, repo, owner string, jobID int64) error {
	path := fmt.Sprintf("/repos/%s/%s/actions/jobs/%d/logs", owner, repo, jobID)

	if err := c.do(ctx, http.MethodGet, path, nil, nil); err != nil {
		return fmt.Errorf("failed to download job logs for job{%d}: %w", jobID, err)
	}
	return nil
}

