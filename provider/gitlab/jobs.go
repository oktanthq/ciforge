// GetJobTrace retrieves the log file (trace) for a specified job.
//
// The caller must have at least Reporter access to the project.
//
// Parameters:
//   - ctx: Request context for cancellation and timeouts.
//   - projectID: Numeric identifier or URL-encoded path of the project.
//   - jobID: Numeric identifier of the job.
//
// Returns the raw log content as a byte slice or an error if the request
// fails or the job has no log file.
func (c *Client) GetJobTrace(ctx context.Context, projectID, jobID int) ([]byte, error) {
	path := fmt.Sprintf("/projects/%d/jobs/%d/trace", projectID, jobID)

	data, err := c.doRaw(ctx, http.MethodGet, path)
	if err != nil {
		return nil, fmt.Errorf("failed to get job trace for job{%d}: %w", jobID, err)
	}
	return data, nil
}

