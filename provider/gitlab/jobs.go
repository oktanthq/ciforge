// ListJobsForProject retrieves all jobs for a specified project.
//
// By default, this request returns 20 results at a time because the API
// results are paginated.
//
// The caller must have read access to the project.
//
// Parameters:
//   - ctx: Request context for cancellation and timeouts.
//   - projectID: Numeric identifier or URL-encoded path of the project.
//   - opts: Optional filtering and sorting parameters.
//
// Returns the jobs associated with the specified project or an error if the
// request fails or the API returns a non-success status.
func (c *Client) ListJobsForProject(ctx context.Context, projectID int, opts *ListJobsForProjectOptions) ([]Job, error) {
	path := fmt.Sprintf("/projects/%d/jobs", projectID)

	if opts != nil {
		path = appendScopeParams(path, opts.Scope)
		path = appendQueryParams(path, opts)
	}

	var resp []Job
	if err := c.do(ctx, http.MethodGet, path, nil, &resp); err != nil {
		return nil, fmt.Errorf("failed to list jobs for project{%d}: %w", projectID, err)
	}
	return resp, nil
}

